/**
 * Standard Hero for AEM Edge Delivery Services / XWalk.
 *
 * Single hero with:
 * - Background image
 * - Heading and description
 * - CTA button
 * - Authorable design controls
 *
 * No geographic personalization.
 */

export default function decorate(block) {
  // Prevent duplicate generated backgrounds.
  block.querySelector('.standard-hero-background')?.remove();

  const originalPicture = block.querySelector('picture');

  // Allow the hero to work without an image.
  if (!originalPicture) {
    block.classList.add('hero-ready');
    return;
  }

  // Create a full-size background layer.
  const background = document.createElement('div');
  background.className = 'standard-hero-background';
  background.setAttribute('aria-hidden', 'true');

  // Clone the responsive image generated by AEM.
  const picture = originalPicture.cloneNode(true);
  const image = picture.querySelector('img');

  if (image) {
    image.loading = 'eager';
    image.alt = '';
  }

  background.append(picture);

  // Find the original image container.
  const imageRow = [...block.children].find(
    (row) => row.contains(originalPicture)
      && !row.querySelector('h2'),
  );

  // Hide only the original image, not the text or CTA.
  if (imageRow) {
    imageRow.hidden = true;
  } else {
    const originalContainer = originalPicture.closest('p');

    if (originalContainer && block.contains(originalContainer)) {
      originalContainer.hidden = true;
    } else {
      originalPicture.hidden = true;
    }
  }

  // Add the generated background behind the content.
  block.prepend(background);

  block.classList.add('has-background', 'hero-ready');
}
